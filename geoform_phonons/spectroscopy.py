"""Spectroscopic mode projections require EXTERNAL response tensors.

Never infer Born effective charges, Raman polarizability derivatives or
Eliashberg alpha^2F from geometry and interatomic force constants alone.
Returned mode activities are relative, not measured intensities.
"""
import math
import numpy as np
from .core import Crystal, PhononInputError


def ir_mode_activity(crystal: Crystal, mode_eigenvector, born_effective_charges, *, polarization=None):
    """Relative Gamma IR activity |sum_k Z*_k e_k/sqrt(m_k)|^2.

    Z* axes: (atom, polarization_cartesian, displacement_cartesian), in |e|.
    The Born-charge acoustic neutrality condition is checked. Inputs must
    originate from an independent electro-optic/DFPT model or measurement.
    """
    n = crystal.n_atoms
    z = np.asarray(born_effective_charges, dtype=float)
    e = np.asarray(mode_eigenvector, dtype=complex)
    if z.shape != (n,3,3) or not np.isfinite(z).all() or e.shape != (3*n,) or not np.isfinite(e).all():
        raise PhononInputError("Born charges Nx3x3 and mode eigenvector 3N required")
    if not np.allclose(z.sum(axis=0), 0, atol=1e-3, rtol=1e-5):
        raise PhononInputError("Born effective charges violate charge-neutrality sum")
    displacements = e.reshape((n,3))/np.sqrt(crystal.masses_amu)[:,None]
    dipole = np.einsum("kab,kb->a", z, displacements)
    if polarization is not None:
        p = np.asarray(polarization, dtype=float)
        if p.shape != (3,) or not np.isfinite(p).all() or np.linalg.norm(p) == 0:
            raise PhononInputError("polarization must be nonzero Cartesian vector")
        dipole = np.dot(p/np.linalg.norm(p), dipole)
    return float(np.sum(np.abs(dipole)**2))


def raman_mode_activity(crystal: Crystal, mode_eigenvector, polarizability_derivatives,
                        incident_polarization, scattered_polarization):
    """Relative polarized Raman activity |e_s^T (d alpha/dQ) e_i|^2.

    Polarizability derivatives axes (atom, displacement, pol_out, pol_in),
    each Cartesian. The tensors are REQUIRED supplied data, not inferred.
    """
    n = crystal.n_atoms
    d = np.asarray(polarizability_derivatives, dtype=float)
    e = np.asarray(mode_eigenvector, dtype=complex)
    if d.shape != (n,3,3,3) or not np.isfinite(d).all() or e.shape != (3*n,) or not np.isfinite(e).all():
        raise PhononInputError("dalpha/du shape Nx3x3x3 and eigenvector 3N required")
    p_in = np.asarray(incident_polarization, dtype=float)
    p_out = np.asarray(scattered_polarization, dtype=float)
    if (p_in.shape != (3,) or p_out.shape != (3,) or not np.isfinite(p_in).all()
            or not np.isfinite(p_out).all() or np.linalg.norm(p_in)==0 or np.linalg.norm(p_out)==0):
        raise PhononInputError("incident/scattered polarization must be nonzero 3-vectors")
    p_in /= np.linalg.norm(p_in)
    p_out /= np.linalg.norm(p_out)
    u = e.reshape((n,3))/np.sqrt(crystal.masses_amu)[:,None]
    alpha_mode = np.einsum("kabc,ka->bc", d, u)
    amp = p_out @ alpha_mode @ p_in
    return float(abs(amp)**2)


def eliashberg_moments(freq_thz, alpha2f):
    """Integrate supplied Eliashberg spectral function: lambda and omega_log.

    alpha2F must use the same THz frequency axis convention as integration;
    no electron-phonon matrix elements are generated by this function.
    The spectral function is treated as dimensionless in the THz convention.
    """
    f = np.asarray(freq_thz, dtype=float)
    a = np.asarray(alpha2f, dtype=float)
    if f.ndim != 1 or len(f) < 2 or a.shape != f.shape or not np.isfinite(f).all() or not np.isfinite(a).all():
        raise PhononInputError("equal finite 1D arrays with >=2 points required")
    if np.any(f <= 0) or np.any(np.diff(f) <= 0) or np.any(a < 0):
        raise PhononInputError("frequency must increase strictly from >0; alpha2F >= 0")
    weight = a/f
    strength = float(np.trapezoid(weight, f))
    lam = 2*strength
    if lam == 0:
        return {"lambda": 0.0, "omega_log_thz": None}
    logmean = float(np.trapezoid(weight*np.log(f), f)/strength)
    return {"lambda": lam, "omega_log_thz": math.exp(logmean)}
